#!/usr/bin/env python3
"""Seeded generator of program-trace tasks written for this study (2026-11-03).

Each task is a short, randomly generated Python function with integer state, a loop
with branching updates, and modular arithmetic so values stay small. The question is
the integer the function returns. Ground truth is obtained by executing the code, so no
model or human grading is involved. Instances are created from a seed after this file is
frozen, so they cannot be in any model's pretraining data.

Difficulty knobs: iterations (loop length), body (statements per iteration), nvars.
`trace` records every variable after each iteration, which supports checkable claims
("after iteration k, b = v") for critique and attribution experiments.

usage (library): make_task(seed, iterations, body, nvars) -> dict
       CLI: progtrace.py SEED ITER BODY NVARS   (prints one task as JSON)
"""
import json
import random
import sys

VARS = ["a", "b", "c", "d"]
MOD = 97


def _expr(rng, vs):
    x, y = rng.choice(vs), rng.choice(vs)
    k = rng.randint(2, 9)
    form = rng.choice([
        f"({x} + {y} * {k}) % {MOD}",
        f"({x} * {k} + {y}) % {MOD}",
        f"({x} - {y} + {k * 3}) % {MOD}",
        f"({x} * {y} + {k}) % {MOD}",
        f"({x} + i * {k}) % {MOD}",
        f"({x} // {k} + {y}) % {MOD}",
    ])
    return form


def _cond(rng, vs):
    x = rng.choice(vs + ["i"])
    k = rng.randint(2, 5)
    r = rng.randint(0, k - 1)
    return rng.choice([f"{x} % {k} == {r}", f"{x} > {rng.randint(20, 70)}", f"({x} + i) % {k} == {r}"])


def make_task(seed, iterations, body, nvars=3):
    rng = random.Random(f"progtrace-{seed}-{iterations}-{body}-{nvars}")
    vs = VARS[:nvars]
    lines = ["def f():"]
    for v in vs:
        lines.append(f"    {v} = {rng.randint(1, 60)}")
    lines.append(f"    for i in range({iterations}):")
    for _ in range(body):
        tgt = rng.choice(vs)
        if rng.random() < 0.5:
            lines.append(f"        if {_cond(rng, vs)}:")
            lines.append(f"            {tgt} = {_expr(rng, vs)}")
            lines.append("        else:")
            lines.append(f"            {rng.choice(vs)} = {_expr(rng, vs)}")
        else:
            lines.append(f"        {tgt} = {_expr(rng, vs)}")
    ret = f"{vs[0]} * 100 + {vs[1]}"
    lines.append(f"    return {ret}")
    src = "\n".join(lines)
    # execute with tracing
    traced = src.replace("def f():", "def f(_t):").replace(
        f"    return {ret}", f"    return {ret}")
    body_lines = traced.split("\n")
    # insert a trace record at the end of every loop iteration
    out = []
    for ln in body_lines:
        out.append(ln)
    loop_idx = next(k for k, ln in enumerate(out) if ln.startswith("    for i in range"))
    ret_idx = next(k for k, ln in enumerate(out) if ln.startswith("    return"))
    out.insert(ret_idx, "        _t.append({" + ", ".join(f"'{v}': {v}" for v in vs) + "})")
    ns = {}
    exec("\n".join(out), ns)  # code is generated by this file, not external input
    trace = []
    ans = ns["f"](trace)
    return {"tid": f"pt_{seed}_{iterations}_{body}_{nvars}", "seed": seed, "iterations": iterations,
            "body": body, "nvars": nvars, "code": src, "answer": int(ans), "trace": trace}


def question(task):
    return ("Here is a Python function.\n\n```python\n" + task["code"] + "\n```\n\n"
            "What integer does f() return?")


if __name__ == "__main__":
    s, it, bd, nv = map(int, sys.argv[1:5])
    print(json.dumps(make_task(s, it, bd, nv), indent=1))
